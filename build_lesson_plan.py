def get_unique_tcs(row):
    """返回该行所有 unique tc(物理 cell),保留原顺序"""
    return row._tr.findall(qn('w:tc'))

def W_tc(tc, text):
    """写入单个 tc(清空后写第一段)"""
    # 清空现有段落
    for p in tc.findall(qn('w:p')):
        # 删除所有 run,只留 paragraph
        for r in p.findall(qn('w:r')):
            p.remove(r)
    # 取或建段落
    paras = tc.findall(qn('w:p'))
    if not paras:
        para = qn('w:p')  # not really; need OxmlElement
        from docx.oxml import OxmlElement
        para = OxmlElement('w:p')
        tc.append(para)
        paras = [para]
    # 写入第一个段落
    p = paras[0]
    # 删除现有 run
    for r in p.findall(qn('w:r')):
        p.remove(r)
    # 插入新 run
    from docx.oxml import OxmlElement
    r = OxmlElement('w:r')
    t = OxmlElement('w:t')
    t.text = text
    t.set(qn('xml:space'), 'preserve')
    r.append(t)
    p.append(r)

def fill_row(row_idx, contents):
    """contents: list of (tc_idx, text); 仅写入指定的 tc"""
    row = tbl.rows[row_idx]
    tcs = get_unique_tcs(row)
    for tc_idx, text in contents:
        W_tc(tcs[tc_idx], text)

